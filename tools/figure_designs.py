def lua_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return '"' + v + '"'
    if isinstance(v, (int, float)):
        return ("%.3f" % v).rstrip("0").rstrip(".") if isinstance(v, float) else str(v)
    raise TypeError(v)


def write_lua():
    lines = [
        "--[[",
        "\tFigureDesigns  (ModuleScript)  ->  ReplicatedStorage/Shared/FigureDesigns",
        "\tAUTOMATISCH ERZEUGT von tools/figure_designs.py. Nicht von Hand ändern.",
        "\t3D-Designs aller Figuren aus Roblox-Parts (Basis-Höhe 4, -Z = vorne).",
        "\tFormat pro Teil: { Form, sx, sy, sz, px, py, pz, Farbe, rx, ry, rz, Material, Färbbar, Transparenz }",
        "\tForm: E = Ellipsoid, B = Block, C = Zylinder (stehend)",
        "]]",
        "",
        "return {",
    ]
    for key, parts in D.items():
        lines.append("\t%s = {" % key)
        for p in parts:
            vals = [p["s"], *p["size"], *p["pos"], p["c"], *p["rot"], p["m"], p["t"], p["a"]]
            lines.append("\t\t{ " + ", ".join(lua_value(v) for v in vals) + " },")
        lines.append("\t},")
    lines.append("}")
    path = os.path.join(ROOT, "src/ReplicatedStorage/Shared/FigureDesigns.lua")
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    return path


