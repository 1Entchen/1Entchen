def P(shape, size, pos, color, rot=(0, 0, 0), mat="SmoothPlastic", tint=True, alpha=0.0):
    return {"s": shape, "size": list(size), "pos": list(pos), "c": color, "rot": list(rot), "m": mat, "t": tint, "a": alpha}


def eyes(y, z, spread, r=0.32, look=0.0):
    out = []
    for side in (-1, 1):
        x = side * spread
        out.append(P("E", (r * 2, r * 2, r * 1.6), (x, y, z), "#FFFFFF", tint=False))
        out.append(P("E", (r, r, r * 0.6), (x + look, y - r * 0.05, z - r * 0.62), "#16101F", tint=False))
        out.append(P("E", (r * 0.32, r * 0.32, r * 0.2), (x + look - r * 0.2, y + r * 0.22, z - r * 0.8), "#FFFFFF", tint=False))
    return out


def mouth(y, z, w=0.5, color="#5A1A2A"):
    return [P("B", (w, 0.09, 0.09), (0, y, z), color, tint=False)]


def cheeks(y, z, spread, color="#FF8A80"):
    return [P("E", (0.3, 0.16, 0.05), (s * spread, y, z), color, tint=False, alpha=0.2) for s in (-1, 1)]


